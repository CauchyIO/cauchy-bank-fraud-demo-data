"""Publish Cauchy Bank's synthetic data to a schema of your workspace.

Run as ``uv run scripts/publish_data.py --profile <PROFILE> --catalog <CATALOG> --schema <SCHEMA>
[--warehouse <id or name>] [--apply] [--show-sql]``. A dry run (the default) prints every file it would upload
and every statement it would run and writes nothing (``--show-sql`` prints each statement in full); ``--apply``
writes; a second apply finds the files, tables, comments and keys in place and prints "nothing to do". Parts,
in order, each an ``ensure_*`` function whose docstring names the lookup and the write:

1. ``local``: ``data/out/cauchy/`` and ``data/out/cauchy.duckdb``, generated by ``bankgen`` when missing
   (``generate`` and ``load``: the same code the ``bankgen all`` command runs);
2. ``schema``: the schema and its volume ``raw``, created when missing (the catalog must exist);
3. ``files``: every Parquet file uploaded to ``/Volumes/<catalog>/<schema>/raw/<table>/`` (``transactions/``
   as its monthly parts), the manifest to ``raw/manifest.json``; a file whose remote size equals its local
   size is left alone, a remote file that is not local is deleted, so each directory holds exactly what the
   generator wrote;
4. ``tables``: ``CREATE OR REPLACE TABLE <catalog>.<schema>.<table> COMMENT '<the dictionary's>' AS SELECT *
   FROM read_files('<dir>', format => 'parquet', schemaEvolutionMode => 'none')`` for every table whose files
   changed or that does not exist (``--force``: all);
5. ``views``: the three views of ``bankgen.load.VIEWS``, replaced when the stored definition differs;
6. ``comments``: the data dictionary (``bankgen.dictionary``) on the schema, every table and view and every
   column, each set where the stored comment differs (``COMMENT ON SCHEMA``, ``COMMENT ON TABLE`` and
   ``COMMENT ON COLUMN``); the catalog's own comment is left alone;
7. ``keys``: the dictionary's informational primary and foreign keys (Unity Catalog does not enforce them),
   each added where its name is missing: a primary key's columns set ``NOT NULL`` first, since a ``CREATE OR
   REPLACE TABLE ... AS SELECT`` leaves every column nullable and drops the table's constraints and the
   foreign keys that refer to it, then the foreign keys. A dry run reads the state before any replace, so it
   lists as in place the keys that its own ``tables`` and ``views`` parts would drop; the apply reads them
   after and adds them;
8. ``counts``: ``SELECT COUNT(*)`` per table and view on the warehouse against the DuckDB file; a mismatch is
   printed and makes the exit code 1.

Statements run through the SQL statement execution API on the warehouse given by ``--warehouse`` (id or
name), else ``DATABRICKS_WAREHOUSE_ID``, else the workspace's single serverless warehouse.
"""


DEFAULT_OUT = Path(__file__).resolve().parents[1] / "data" / "out"
BANK = "cauchy"  # the generator's profile
STATEMENT_TIMEOUT_S = 1800

T = TypeVar("T")


class PublishError(RuntimeError):
    """The publish cannot go on: a missing prerequisite, a failed statement."""


@dataclass(frozen=True)
class Line:
    """One thing the run found, did or would do, as printed."""

    part: str
    state: str  # exists, done, would, mismatch, info, skipped
    what: str


@dataclass(frozen=True)
class Result:
    """A statement's columns (name, type text) and rows, every value a string or None as the API sends it."""

    columns: list[tuple[str, str]]
    rows: list[list[str | None]]

    def scalar(self) -> str | None:
        return self.rows[0][0] if self.rows and self.rows[0] else None


# --- The statement execution API ----------------------------------------------------------------


def run_sql(
    w: WorkspaceClient,
    warehouse_id: str,
    statement: str,
    *,
    catalog: str,
    schema: str,
    parameters: Sequence[StatementParameterListItem] = (),
    poll_s: float = 2.0,
    timeout_s: float = STATEMENT_TIMEOUT_S,
    sleep: Callable[[float], None] = time.sleep,
) -> Result:
    """One statement on the warehouse with ``catalog`` and ``schema`` as the defaults, so the
    unqualified names the queries use resolve; waits up to the API's 50 s inline, then polls
    ``get_statement``; follows the result chunks; a failed statement raises ``PublishError``."""
    response = w.statement_execution.execute_statement(
        statement=statement,
        warehouse_id=warehouse_id,
        catalog=catalog,
        schema=schema,
        parameters=list(parameters) or None,
        wait_timeout="50s",
        on_wait_timeout=ExecuteStatementRequestOnWaitTimeout.CONTINUE,
    )
    started = time.monotonic()
    while response.status and response.status.state in (StatementState.PENDING, StatementState.RUNNING):
        if time.monotonic() - started > timeout_s:
            raise PublishError(f"statement {response.statement_id} still running after {timeout_s:.0f}s")
        sleep(poll_s)
        response = w.statement_execution.get_statement(statement_id=response.statement_id or "")
    state = response.status.state if response.status else None
    if state != StatementState.SUCCEEDED:
        error = response.status.error if response.status else None
        message = error.message if error and error.message else str(state)
        raise PublishError(
            f"statement failed ({state.value if state else '?'}): {message}\n  {statement.strip()[:300]}"
        )
    columns = [
        (c.name or "", c.type_text or (c.type_name.value if c.type_name else "STRING"))
        for c in ((response.manifest.schema.columns if response.manifest and response.manifest.schema else None) or [])
    ]
    rows: list[list[str | None]] = []
    chunk = response.result
    while chunk is not None:
        rows.extend([list(r) for r in chunk.data_array or []])
        if chunk.next_chunk_index is None:
            break
        chunk = w.statement_execution.get_statement_result_chunk_n(
            statement_id=response.statement_id or "", chunk_index=chunk.next_chunk_index
        )
    return Result(columns, rows)


def resolve_warehouse(w: WorkspaceClient, wanted: str | None, env: Mapping[str, str]) -> tuple[str, str]:
    """The warehouse id and name: ``wanted`` matched on id, then on name; else the variable
    ``DATABRICKS_WAREHOUSE_ID``; else the one serverless warehouse of the workspace. Anything else
    is an error that lists the serverless warehouses, so the caller can name one."""
    warehouses = [(e.id or "", e.name or "", bool(e.enable_serverless_compute)) for e in w.warehouses.list()]
    chosen = wanted or env.get(WAREHOUSE_VARIABLE)
    if chosen:
        for wid, name, _ in warehouses:
            if chosen in (wid, name):
                return wid, name
        raise PublishError(f"no warehouse with id or name {chosen!r}; {_listed(warehouses)}")
    serverless = [(wid, name) for wid, name, is_serverless in warehouses if is_serverless]
    if len(serverless) == 1:
        return serverless[0]
    raise PublishError(f"pass --warehouse or set {WAREHOUSE_VARIABLE}; {_listed(warehouses)}")


def _listed(warehouses: Sequence[tuple[str, str, bool]]) -> str:
    serverless = ", ".join(f"{name} ({wid})" for wid, name, is_serverless in warehouses if is_serverless)
    return f"serverless warehouses: {serverless or 'none'}"


# --- The run ----------------------------------------------------------------------------------------


@dataclass(frozen=True)
class LocalFile:
    """A generated file and where it goes in the volume."""

    table: str  # the table it belongs to, or "" for the manifest
    path: Path
    remote: str

    @property
    def size(self) -> int:
        return self.path.stat().st_size


class Publish:
    """The client, the target schema, the mode, and what the run has printed so far.

    Every write goes through ``write``, which in a dry run only prints what it would do: that one
    gate is what makes the dry run read-only.
    """

    def __init__(
        self,
        w: WorkspaceClient,
        *,
        catalog: str,
        schema: str,
        warehouse_id: str,
        apply: bool,
        out_root: Path = DEFAULT_OUT,
        force: bool = False,
        generator: Callable[[str, Path], None] | None = None,
        sleep: Callable[[float], None] = time.sleep,
        out: Callable[[str], None] = print,
        show_sql: bool = False,
    ) -> None:
        self.w = w
        self.bank = BANK
        self.catalog = catalog
        self.schema = schema
        self.warehouse_id = warehouse_id
        self.apply = apply
        self.out_root = out_root
        self.force = force
        self.generator = generator or generate_and_load
        self.sleep = sleep
        self.out = out
        self.show_sql = show_sql
        self.described: Described = describe(BANK)
        self.part = ""
        self.lines: list[Line] = []
        self.changed_tables: set[str] = set()

    # -- printing and the gate --

    def note(self, state: str, what: str) -> None:
        self.lines.append(Line(self.part, state, what))
        self.out(f"  [{state}] {what}")

    def exists(self, what: str) -> None:
        self.note("exists", what)

    def write(self, what: str, call: Callable[..., T], *args: Any, **kwargs: Any) -> T | None:
        """Make the call and print ``what``; a dry run only prints."""
        if not self.apply:
            self.note("would", what)
            return None
        result = call(*args, **kwargs)
        self.note("done", what)
        return result

    def statement(self, what: str, sql: str) -> None:
        """Run one write statement on the warehouse through ``write``; ``--show-sql`` prints it in full."""
        self.write(what, self.sql, sql)
        if self.show_sql:
            self.out(f"      {sql}")

    def changes_in(self, part: str) -> int:
        return sum(1 for line in self.lines if line.part == part and line.state in ("done", "would"))

    def count(self, state: str) -> int:
        return sum(1 for line in self.lines if line.state == state)

    # -- names --

    @property
    def volume_root(self) -> str:
        return f"/Volumes/{self.catalog}/{self.schema}/{VOLUME}"

    def full_name(self, table: str) -> str:
        return f"{self.catalog}.{self.schema}.{table}"

    @property
    def local_dir(self) -> Path:
        return self.out_root / self.bank

    @property
    def db_path(self) -> Path:
        return self.out_root / f"{self.bank}.duckdb"

    def sql(self, statement: str, parameters: Sequence[StatementParameterListItem] = ()) -> Result:
        return run_sql(
            self.w,
            self.warehouse_id,
            statement,
            catalog=self.catalog,
            schema=self.schema,
            parameters=parameters,
            sleep=self.sleep,
        )

    @property
    def caller(self) -> str:
        return self.w.current_user.me().user_name or ""


def generate_and_load(bank: str, out_root: Path) -> None:
    """What ``bankgen all`` does without the story checks: generate, then load into DuckDB."""
    generate(bank, out_root)
    load(bank, out_root)


# --- 1. The local data ----------------------------------------------------------------------------


def local_files(p: Publish) -> list[LocalFile]:
    """Every file the generator wrote, with its place in the volume: ``raw/<table>/<table>.parquet``,
    the ledger's monthly parts under ``raw/transactions/``, the manifest at ``raw/manifest.json``."""
    root = p.volume_root
    files = [LocalFile(t, p.local_dir / f"{t}.parquet", f"{root}/{t}/{t}.parquet") for t in TABLE_ORDER]
    files += [
        LocalFile(TRANSACTIONS, part, f"{root}/{TRANSACTIONS}/{part.name}")
        for part in sorted((p.local_dir / TRANSACTIONS).glob("*.parquet"))
    ]
    files.append(LocalFile("", p.local_dir / MANIFEST, f"{root}/{MANIFEST}"))
    return files


def tables_of(p: Publish) -> list[str]:
    return [*TABLE_ORDER, TRANSACTIONS]


def missing_local(p: Publish) -> list[Path]:
    expected = [f.path for f in local_files(p) if f.table != TRANSACTIONS] + [p.db_path]
    missing = [path for path in expected if not path.is_file()]
    if not list((p.local_dir / TRANSACTIONS).glob("*.parquet")):
        missing.append(p.local_dir / TRANSACTIONS)
    return missing


def ensure_local(p: Publish) -> bool:
    """``data/out/<bank>/`` and the DuckDB file looked up on disk; generated with ``bankgen`` when
    anything is missing. True when the data is there after this call."""
    missing = missing_local(p)
    if not missing:
        manifest = json.loads((p.local_dir / MANIFEST).read_text(encoding="utf-8"))
        p.exists(
            f"{p.local_dir} (seed {manifest.get('seed')}, {manifest.get('n_customers')} customers,"
            f" generator {manifest.get('generator_version')}) and {p.db_path.name}"
        )
        return True
    names = ", ".join(path.name for path in missing[:4]) + (", ..." if len(missing) > 4 else "")
    p.write(f"generate {p.bank} into {p.out_root} (missing: {names})", p.generator, p.bank, p.out_root)
    if p.apply and (still := missing_local(p)):
        raise PublishError(f"bankgen did not write {still[0]}")
    return p.apply


# --- 2. The schema and its volume ------------------------------------------------------------------


def ensure_schema(p: Publish) -> bool:
    """The catalog looked up with ``catalogs.get`` (it must exist: creating a catalog is the workspace's
    call); the schema with ``schemas.get`` and the volume ``raw`` with ``volumes.read``; each created with the
    SDK (``schemas.create``, ``volumes.create``, a managed volume) when missing, since a statement cannot run
    with a default schema that does not exist yet. True when the schema is there after this call."""
    try:
        p.w.catalogs.get(name=p.catalog)
    except NotFound as error:
        raise PublishError(f"catalog {p.catalog} does not exist; create it or pass another --catalog") from error
    full_schema = f"{p.catalog}.{p.schema}"
    try:
        p.w.schemas.get(full_name=full_schema)
        p.exists(f"schema {full_schema}")
    except NotFound:
        p.write(f"create schema {full_schema}", p.w.schemas.create, name=p.schema, catalog_name=p.catalog)
        if not p.apply:
            p.write(f"create volume {full_schema}.{VOLUME}", lambda: None)
            return False
    full_volume = f"{full_schema}.{VOLUME}"
    try:
        p.w.volumes.read(name=full_volume)
        p.exists(f"volume {full_volume}")
    except NotFound:
        p.write(
            f"create volume {full_volume}",
            p.w.volumes.create,
            catalog_name=p.catalog,
            schema_name=p.schema,
            name=VOLUME,
            volume_type=VolumeType.MANAGED,
        )
    return True


# --- 3. The files in the volume -----------------------------------------------------------------


def remote_sizes(p: Publish, directory: str) -> dict[str, int]:
    """The files directly under ``directory`` with their sizes; empty when the directory is not there."""
    try:
        entries = list(p.w.files.list_directory_contents(directory_path=directory))
    except NotFound:
        return {}
    return {e.name or "": e.file_size or 0 for e in entries if not e.is_directory}


def upload(p: Publish, local: Path, remote: str) -> None:
    with local.open("rb") as handle:
        p.w.files.upload(file_path=remote, contents=handle, overwrite=True)


def ensure_volume_files(p: Publish) -> None:
    """Each directory listed with ``files.list_directory_contents``; a local file uploaded with
    ``files.upload`` (overwrite) unless a remote file of the same name and size is there and
    ``--force`` is off; a remote file the generator did not write deleted with ``files.delete``.
    A table whose directory changed is remembered for the ``tables`` part."""
    files = local_files(p)
    directories = sorted({f.remote.rsplit("/", 1)[0] for f in files})
    for directory in directories:
        here = [f for f in files if f.remote.rsplit("/", 1)[0] == directory]
        remote = remote_sizes(p, directory)
        for f in here:
            name = f.remote.rsplit("/", 1)[1]
            if not p.force and remote.get(name) == f.size:
                p.exists(f"{f.remote} ({f.size:,} bytes)")
                continue
            p.write(f"upload {f.path.name} -> {f.remote} ({f.size:,} bytes)", upload, p, f.path, f.remote)
            if f.table:
                p.changed_tables.add(f.table)
        for name in sorted(set(remote) - {f.remote.rsplit("/", 1)[1] for f in here}):
            if directory == p.volume_root:
                p.note("info", f"{directory}/{name} is not the generator's; left alone")
                continue
            p.write(f"delete stale {directory}/{name}", p.w.files.delete, file_path=f"{directory}/{name}")
            table = directory.rsplit("/", 1)[1]
            p.changed_tables.add(table)


# --- 4. The tables --------------------------------------------------------------------------------


def ctas(p: Publish, table: str) -> str:
    directory = f"{p.volume_root}/{table}/"
    return (
        f"CREATE OR REPLACE TABLE {p.full_name(table)} COMMENT {sql_string(p.described.tables[table])} AS\n"
        f"SELECT * FROM read_files('{directory}', format => 'parquet', schemaEvolutionMode => 'none')"
    )


def table_exists(p: Publish, table: str) -> bool:
    return bool(p.w.tables.exists(full_name=p.full_name(table)).table_exists)


def ensure_tables(p: Publish) -> None:
    """Each table looked up with ``tables.exists`` and created or replaced by the CTAS statement
    when it is missing, when its files changed in this run, or with ``--force``.
    ``schemaEvolutionMode => 'none'`` keeps ``read_files`` from adding ``_rescued_data``."""
    for table in tables_of(p):
        full = p.full_name(table)
        if table_exists(p, table) and table not in p.changed_tables and not p.force:
            p.exists(f"table {full}")
            continue
        p.statement(f"create or replace table {full} from {p.volume_root}/{table}/", ctas(p, table))


# --- 5. The views ---------------------------------------------------------------------------------


def view_sql(sql: str) -> str:
    """The generator's view body, one space per run of whitespace, as stored and compared."""
    return " ".join(sql.split())


def stored_view(p: Publish, view: str) -> str | None:
    """The body of the view as the catalog stores it, None when the view is not there."""
    try:
        info = p.w.tables.get(full_name=p.full_name(view))
    except NotFound:
        return None
    return view_sql(info.view_definition or "")


def ensure_views(p: Publish) -> None:
    """Each view of ``bankgen.load.VIEWS`` looked up with ``tables.get`` and created or replaced
    with ``CREATE OR REPLACE VIEW`` when it is missing or its stored definition differs from the
    generator's; the body is sent as is, with unqualified table names, which the statement's
    default catalog and schema resolve."""
    for view, sql in VIEWS.items():
        full = p.full_name(view)
        body = view_sql(sql)
        if stored_view(p, view) == body and not p.force:
            p.exists(f"view {full}")
            continue
        p.statement(f"create or replace view {full}", f"CREATE OR REPLACE VIEW {full} AS {body}")


# --- 6. The comments ------------------------------------------------------------------------------


def stored_relation(p: Publish, name: str) -> TableInfo | None:
    """The table or view as the catalog stores it (comment, columns, constraints), None when it is not there."""
    try:
        return p.w.tables.get(full_name=p.full_name(name))
    except NotFound:
        return None


def ensure_comments(p: Publish) -> None:
    """The schema's comment read with ``schemas.get``, set with ``COMMENT ON SCHEMA`` when it differs from the
    dictionary's (the catalog's own comment is left alone); each table and view
    read with ``tables.get`` and given ``COMMENT ON TABLE`` and one ``COMMENT ON COLUMN`` per column whose stored
    comment differs (``bankgen.dictionary.comment_statements``, the statements DuckDB runs). A column the
    dictionary does not describe is reported, not guessed."""
    full_schema = f"{p.catalog}.{p.schema}"
    if p.w.schemas.get(full_name=full_schema).comment == p.described.schema:
        p.exists(f"comment on schema {full_schema}")
    else:
        p.statement(
            f"comment on schema {full_schema}", f"COMMENT ON SCHEMA {full_schema} IS {sql_string(p.described.schema)}"
        )
    for name in p.described.tables:
        info = stored_relation(p, name)
        stored = {c.name or "": c.comment for c in (info.columns or [])} if info else {}
        statements = comment_statements(p.described, name, p.full_name)
        have = [None if info is None else info.comment, *(stored.get(c) for c in p.described.columns[name])]
        want = [p.described.tables[name], *p.described.columns[name].values()]
        todo = [sql for sql, h, w in zip(statements, have, want, strict=True) if h != w]
        for column in sorted(set(stored) - set(p.described.columns[name])):
            p.note("info", f"{p.full_name(name)}.{column} is not in the dictionary; left alone")
        if not todo:
            p.exists(f"comments on {p.full_name(name)}")
            continue
        for sql in todo:
            target = sql.split(" IS ", 1)[0].removeprefix("COMMENT ON ").lower()
            p.statement(f"comment on {target}", sql)


# --- 7. The keys ----------------------------------------------------------------------------------


def primary_key_name(table: str) -> str:
    return f"{table}_pk"


def foreign_key_name(table: str, column: str) -> str:
    return f"{table}_{column}_fk"


def constraint_names(info: TableInfo | None) -> set[str]:
    names: set[str] = set()
    for c in (info.table_constraints or []) if info else []:
        for named in (c.primary_key_constraint, c.foreign_key_constraint, c.named_table_constraint):
            if named is not None and named.name:
                names.add(named.name)
    return names


def ensure_keys(p: Publish) -> None:
    """Each table read with ``tables.get``; a primary key whose name is missing added with ``ALTER TABLE ... ALTER
    COLUMN ... SET NOT NULL`` for each nullable key column and ``ALTER TABLE ... ADD CONSTRAINT <table>_pk PRIMARY
    KEY``; then each foreign key whose name is missing with ``ADD CONSTRAINT <table>_<column>_fk FOREIGN KEY ...
    REFERENCES``. A constraint is found by its name only; one the dictionary does not name is left alone. The keys
    are informational (``NOT ENFORCED``, ``NORELY``, the defaults): readers and tools see the joins, no query is
    rewritten on them."""
    tables = [t for t in p.described.tables if not RELATIONS[t].view]
    infos = {t: stored_relation(p, t) for t in tables}
    for table in tables:
        key = RELATIONS[table].primary_key
        if not key:
            continue
        full, name, info = p.full_name(table), primary_key_name(table), infos[table]
        if name in constraint_names(info):
            p.exists(f"primary key {name} on {full}")
            continue
        nullable = {c.name: c.nullable is not False for c in (info.columns or [])} if info else {}
        for column in key:
            if nullable.get(column, True):
                p.statement(f"not null {full}.{column}", f"ALTER TABLE {full} ALTER COLUMN {column} SET NOT NULL")
        p.statement(
            f"primary key {name} on {full} ({', '.join(key)})",
            f"ALTER TABLE {full} ADD CONSTRAINT {name} PRIMARY KEY ({', '.join(key)})",
        )
    for table in tables:
        full, info = p.full_name(table), infos[table]
        for fk in RELATIONS[table].foreign_keys:
            name = foreign_key_name(table, fk.column)
            if name in constraint_names(info):
                p.exists(f"foreign key {name} on {full}")
                continue
            p.statement(
                f"foreign key {name} on {full} ({fk.column} -> {fk.parent}.{fk.parent_column})",
                f"ALTER TABLE {full} ADD CONSTRAINT {name} FOREIGN KEY ({fk.column}) "
                f"REFERENCES {p.full_name(fk.parent)} ({fk.parent_column})",
            )


# --- 8. The counts --------------------------------------------------------------------------------


def local_counts(db_path: Path, names: Sequence[str]) -> dict[str, int]:
    """``SELECT COUNT(*)`` per table and view on the bank's DuckDB file, read-only."""
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        counts: dict[str, int] = {}
        for name in names:
            row = con.execute(f"SELECT COUNT(*) FROM {name}").fetchone()
            counts[name] = int(row[0]) if row else -1
        return counts
    finally:
        con.close()


def remote_count(p: Publish, name: str) -> int:
    return int(p.sql(f"SELECT COUNT(*) FROM {p.full_name(name)}").scalar() or -1)


def check_counts(p: Publish) -> bool:
    """Every table and view counted on both sides and printed as one table; a dry run prints the
    DuckDB counts only. True when every count matches."""
    names = [*tables_of(p), *VIEWS]
    local = local_counts(p.db_path, names)
    ok = True
    p.out(f"  {'name':<26}{'duckdb':>12}{'workspace':>12}")
    for name in names:
        if not p.apply:
            p.out(f"  {name:<26}{local[name]:>12,}{'after apply':>12}")
            continue
        remote = remote_count(p, name)
        match = remote == local[name]
        ok &= match
        p.out(f"  {name:<26}{local[name]:>12,}{remote:>12,}  {'ok' if match else 'MISMATCH'}")
        if not match:
            p.note("mismatch", f"{p.full_name(name)}: {remote:,} rows in the workspace, {local[name]:,} in DuckDB")
    if p.apply and ok:
        p.note("info", f"{len(names)} counts match")
    return ok


# --- The run --------------------------------------------------------------------------------------

PARTS: dict[str, Callable[[Publish], Any]] = {
    "local": ensure_local,
    "schema": ensure_schema,
    "files": ensure_volume_files,
    "tables": ensure_tables,
    "views": ensure_views,
    "comments": ensure_comments,
    "keys": ensure_keys,
    "counts": check_counts,
}


def run(p: Publish, only: Sequence[str] = ()) -> bool:
    """Every part in order, or only those named; stops after ``local`` when the data is not there yet, and
    after ``schema`` when the schema is not (a dry run of a first publish). True when the counts matched or were
    not checked."""
    ok = True
    for name, part in PARTS.items():
        if only and name not in only:
            continue
        p.part = name
        p.out(f"\n== {name}")
        result = part(p)
        if name == "local" and result is False:
            p.out("  the other parts wait on the generated data")
            break
        if name == "schema" and result is False:
            p.out("  the other parts wait on the schema")
            break
        if name == "counts":
            ok = bool(result)
        if p.changes_in(name) == 0 and name != "counts":
            p.out("  nothing to do")
    return ok


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--profile", required=True, help="the Databricks CLI profile of the workspace; never guessed")
    parser.add_argument("--catalog", required=True, help="an existing Unity Catalog catalog")
    parser.add_argument("--schema", required=True, help="the schema to publish into; created when missing")
    parser.add_argument("--apply", action="store_true", help="upload and create what is missing (default: dry run)")
    parser.add_argument("--force", action="store_true", help="re-upload every file and replace every table and view")
    parser.add_argument(
        "--warehouse", help=f"serverless SQL warehouse id or name (default: {WAREHOUSE_VARIABLE}, else the only one)"
    )
    parser.add_argument("--show-sql", action="store_true", help="print every write statement in full")
    parser.add_argument("--part", action="append", default=[], choices=sorted(PARTS), help="run only this part")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="the generator's output root (data/out)")
    args = parser.parse_args(argv)

    w = WorkspaceClient(profile=args.profile)
    mode = "apply" if args.apply else "dry run, nothing is written"
    p: Publish | None = None
    try:
        warehouse_id, warehouse_name = resolve_warehouse(w, args.warehouse, os.environ)
        p = Publish(
            w,
            catalog=args.catalog,
            schema=args.schema,
            warehouse_id=warehouse_id,
            apply=args.apply,
            out_root=args.out,
            force=args.force,
            show_sql=args.show_sql,
        )
        print(
            f"workspace {w.config.host}, profile {args.profile}, signed in as {p.caller};"
            f" warehouse {warehouse_name} ({warehouse_id}); {p.catalog}.{p.schema}; {mode}"
        )
        ok = run(p, only=args.part)
    except Exception as error:
        print(f"\nSTOPPED in {p.part if p else 'setup'}: {type(error).__name__}: {error}")
        return 2
    changes = p.count("done") + p.count("would")
    print(
        f"\n{changes} changes {'made' if args.apply else 'to make'}, {p.count('exists')} in place,"
        f" {p.count('mismatch')} count mismatches"
    )
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
